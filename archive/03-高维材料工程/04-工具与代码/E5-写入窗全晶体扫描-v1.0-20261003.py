rows, inwin = [], []
for name, modes, kind, acc in LIB:
    for m in modes:
        thz = round(m * C, 2)
        dev = 100 * (thz - F1) / F1
        hit = WIN_LO <= m <= WIN_HI
        r = {"材料": name, "模_cm-1": m, "THz": thz, "偏差%": round(dev, 2),
             "性质": kind, "库精度": acc, "窗内": hit}
        rows.append(r)
        if hit:
            inwin.append(r)

# 邻近带（±2% = 992.5-1081）
near = [r for r in rows if abs(r["偏差%"]) <= 2.0]

