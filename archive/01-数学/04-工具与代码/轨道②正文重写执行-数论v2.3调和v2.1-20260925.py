def apply(path_old, path_new, banner_new, banner_old, repls):
    with io.open(path_old, encoding='utf-8') as f:
        text = f.read()
    t = text
    for i, (old, new, tag) in enumerate(repls):
        n = t.count(old)
        if n == 0:
            report.append(f"  [{tag}] 未命中（0 处）——人工复核")
        else:
            t = t.replace(old, new)
            report.append(f"  [{tag}] 命中 {n} 处，已替换")
    with io.open(path_new, 'w', encoding='utf-8', newline='') as f:
        f.write(banner_new + "\n" + t)
    # 旧版头注存档
    with io.open(path_old, encoding='utf-8') as f:
        old_text = f.read()
    if not old_text.startswith("> 【"):
        with io.open(path_old, 'w', encoding='utf-8', newline='') as f:
            f.write(banner_old + "\n" + old_text)
        report.append(f"  旧版头注存档：已写入 {os.path.basename(path_old)}")
    else:
        report.append(f"  旧版已有头注，跳过 {os.path.basename(path_old)}")

