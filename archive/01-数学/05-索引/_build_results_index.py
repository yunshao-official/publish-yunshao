def version_chains(rows, top=18):
    groups = {}
    for r in rows:
        if r["ext"] != "md":
            continue
        groups.setdefault((r["area"], r["family"]), []).append(r)
    multi = [(k, v) for k, v in groups.items() if len(v) > 1]
    multi.sort(key=lambda x: -len(x[1]))
    out = []
    for (area, fam), g in multi[:top]:
        def key(r):
            v = r["version"]
            return (tuple(int(x) for x in v.split(".")) if v else (-1,), r["date"])
        best = max(g, key=key)
        out.append((area, fam, len(g), best["path"], best["date"]))
    return len(multi), len(groups), out


